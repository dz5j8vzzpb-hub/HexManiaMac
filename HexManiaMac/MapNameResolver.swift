import Foundation

struct MapPoint: Hashable {
    let group: Int
    let map: Int
}

/// Logical Hoenn gym locations. Membership is defined exclusively by map
/// coordinates, so trainer metadata and party contents never affect it.
enum EmeraldGymLocationLayout {
    private struct Gym {
        let maps: Set<MapPoint>
        let englishName: String
        let italianName: String
    }

    private static let gyms: [Gym] = [
        Gym(maps: [MapPoint(group: 11, map: 3)], englishName: "Rustboro Gym", italianName: "Palestra di Ferrugipoli"),
        Gym(maps: [MapPoint(group: 3, map: 3)], englishName: "Dewford Gym", italianName: "Palestra di Bluruvia"),
        Gym(maps: [MapPoint(group: 10, map: 0)], englishName: "Mauville Gym", italianName: "Palestra di Ciclamipoli"),
        Gym(maps: [MapPoint(group: 4, map: 1), MapPoint(group: 4, map: 2)], englishName: "Lavaridge Gym", italianName: "Palestra di Cuordilava"),
        Gym(maps: [MapPoint(group: 8, map: 1)], englishName: "Petalburg Gym", italianName: "Palestra di Petalipoli"),
        Gym(maps: [MapPoint(group: 12, map: 1)], englishName: "Fortree Gym", italianName: "Palestra di Forestopoli"),
        Gym(maps: [MapPoint(group: 14, map: 0)], englishName: "Mossdeep Gym", italianName: "Palestra di Verdeazzupoli"),
        Gym(maps: [MapPoint(group: 15, map: 0), MapPoint(group: 15, map: 1)], englishName: "Sootopolis Gym", italianName: "Palestra di Ceneride")
    ]

    static func locationName(for point: MapPoint, language: AppLanguage) -> String? {
        guard let gym = gyms.first(where: { $0.maps.contains(point) }) else { return nil }
        return language == .italian ? gym.italianName : gym.englishName
    }
}

