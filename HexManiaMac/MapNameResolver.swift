final class MapNameResolver {
    struct Name {
        let english: String
        let italian: String
    }

    static let shared = MapNameResolver()

    private let names: [MapPoint: Name]

    private init() {
        var entries: [MapPoint: Name] = [:]
        for (group, groupNames) in MapNameResolverTable.groups.enumerated() {
            for (map, name) in groupNames.enumerated() {
                entries[MapPoint(group: group, map: map)] = Name(english: name.english, italian: name.italian)
            }
        }
        names = entries
    }

    func mapName(group: Int, map: Int, language: AppLanguage) -> String {
        let name = names[MapPoint(group: group, map: map)]
        let candidate = language == .italian ? name?.italian : name?.english
        if let candidate, !candidate.isEmpty {
            return candidate
        }
        return language == .italian ? "Mappa \(group).\(map)" : "Map \(group).\(map)"
    }

    func mapName(group: Int, map: Int) -> String {
        let stored = UserDefaults.standard.string(forKey: "appLanguage")
        let language = AppLanguage.from(stored ?? AppLanguage.italian.rawValue)
        return mapName(group: group, map: map, language: language)
    }
}
